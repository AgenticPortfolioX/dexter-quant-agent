import os
import sys
from datetime import datetime
import pytz

# Paths
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIGNALS_LOG = r"C:\Users\jmgra\antigravityagents\.agent\reporting-repo\dexter-quant\logs\live_testing\signals.log"
REPORT_DIR = r"C:\Users\jmgra\antigravityagents\.agent\reporting-repo\dexter-quant\logs\audit"
EST = pytz.timezone('US/Eastern')

def run_audit():
    if not os.path.exists(REPORT_DIR):
        os.makedirs(REPORT_DIR, exist_ok=True)
        
    now = datetime.now(EST)
    today_str = now.strftime("%Y-%m-%d")
    
    print(f"[{now.strftime('%H:%M:%S EST')}] Running Post-Market Session Audit...")
    
    signals = []
    if os.path.exists(SIGNALS_LOG):
        with open(SIGNALS_LOG, "r", encoding='utf-8') as f:
            for line in f:
                if today_str in line:
                    signals.append(line.strip())
                    
    # Generate Audit Report
    report_content = f"""# 📝 SESSION AUDIT: {today_str}
> **Audit Timestamp**: {now.strftime("%Y-%m-%d %H:%M:%S EST")}

## 📊 SESSION SUMMARY
- **Total Signals Detected**: {len(signals)}
- **Market Regime**: (Review Morning Report)

## 🎯 SIGNAL RECAP
"""
    if signals:
        for s in signals:
            report_content += f"- {s}\n"
    else:
        report_content += "*No signals recorded today.*\n"
        
    report_content += """
## 🧠 PSYCHOLOGICAL REVIEW (User Input Required)
- **Did I follow every rule?** (Yes/No)
- **Did I experience 'Tilt' triggers?** (Hunger, Fatigue, Frustration)
- **Mistake of the Day**: 

## 📏 RULE AUDIT & GAP ANALYSIS (Proposal #5)
- **Rule Audit**: Document every instance where a rule was bent (even if profitable).
    - *Input*: 
- **Gap Analysis**: Document "The Trade I Missed" and why.
    - *Input*: 

## ⚖️ ALPHA EXTRACTION
- **What one micro-adjustment would have improved today?**
- **Was I too passive or too aggressive?**

---
*Generated by Dexter | Session Audit Module | Research Proposal #5 Integrated*
"""
    
    filepath = os.path.join(REPORT_DIR, f"audit_{today_str}.md")
    with open(filepath, "w", encoding='utf-8') as f:
        f.write(report_content)
        
    print(f"✅ Audit report saved to: {filepath}")
    return filepath

if __name__ == "__main__":
    run_audit()
